/**
 * Mission 14 — Gate 3: Concurrency (Tier-2 CBraMod foundation embed path).
 *
 * Goals:
 *  - measure successful / failed requests, p50/p95/p99 latency, under a ramp of
 *    concurrency (1 → 5 → 10 → 20 concurrent in-flight requests);
 *  - prove requests do not interfere (each returns a valid 200-D embedding);
 *  - observe ONNX-session reuse safety: foundation.server.ts uses a single cached
 *    `cachedAdapter` (singleton ONNXAdapter) shared across requests — we assert no
 *    cross-request corruption (all returned vectors stay L2-normalised, dim=200) when
 *    many requests share it concurrently.
 *
 * Strategy (matches -foundation.test.ts idiom): the route is invoked directly via
 * `Route.options.server.handlers.POST({request, context})` with `onnxruntime-node`
 * mocked (no native forward) + a mocked NeuralVectorIndex. Concurrency is generated by
 * `Promise.all` over N in-flight `callFoundation` calls. This exercises the real route
 * handler + real (mocked) adapter + real auth/rate-limit mocks, isolating the
 * concurrency variable to the route + its shared singleton session.
 *
 * We do NOT touch production concurrency limits — we only observe.
 */

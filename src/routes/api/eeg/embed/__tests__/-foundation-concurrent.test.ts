const { Route } = await import("../foundation");
type PostHandler = (ctx: { request: Request; context: unknown }) => Promise<Response>;
function callFoundation(request: Request) {
  const handlers = Route.options.server!.handlers as unknown as { POST: PostHandler };
  return handlers.POST({ request, context: {} });
}

function fakeSupabase() {
  return {
    from: () => ({
      insert: () => ({ select: async () => ({ data: [{ id: "x" }], error: null }) }),
    }),
  };
}

function csvFile(name = "signal.csv", channels = 19, rows = 1200): File {
  const lines: string[] = [];
  for (let r = 0; r < rows; r++) {
    lines.push(
      Array.from({ length: channels }, (_, c) => Math.sin((r + c) * 0.1).toFixed(4)).join(","),
    );
  }
  return new File([lines.join("\n")], name, { type: "text/csv" });
}

function uploadRequest(form: FormData): Request {
  const headers: Record<string, string> = { authorization: "Bearer test-token" };
  return new Request("http://localhost/api/eeg/embed/foundation", {
    method: "POST",
    body: form,
    headers,
  });
}

function buildRequest(i: number): Request {
  const form = new FormData();
  form.set("file", csvFile(`signal_${i}.csv`, 19, 1200));
  form.set("sampleRate", "250");
  return uploadRequest(form);
}

function percentile(sorted: number[], p: number): number {
  if (sorted.length === 0) return 0;
  const idx = Math.min(sorted.length - 1, Math.max(0, Math.ceil((p / 100) * sorted.length) - 1));
  return sorted[idx];
}

describe("Gate 3: concurrency against the Tier-2 foundation route", () => {
  beforeEach(() => {
    mockAuthenticateRequest.mockReset();
    mockAuthenticateRequest.mockResolvedValue({
      userId: `u-${Math.random().toString(36).slice(2)}`,
      supabase: fakeSupabase(),
    });
    mockEmbedFoundationWindows.mockReset();
    mockEmbedFoundationWindows.mockImplementation(async () => [
      {
        vector: Array.from({ length: 200 }, () => Math.random()),
        dim: 200,
        modelId: "onnx-cbramod-foundation-200d",
        durationMs: 5,
        fellBack: false,
        normalized: true,
      },
    ]);
    addMock.mockClear();
    addMock.mockResolvedValue(undefined);
  });

  for (const n of [1, 5, 10, 20]) {
    it(`handles ${n} concurrent requests with no interference`, async () => {
      const reqs = Array.from({ length: n }, (_, i) => buildRequest(i));
      const t0 = performance.now();
      const responses = await Promise.all(reqs.map((r) => callFoundation(r)));
      const elapsed = performance.now() - t0;

      // All requests must succeed (no cross-request failures / corruption).
      const statuses = responses.map((r) => r.status);
      const failures = statuses.filter((s) => s !== 200);
      expect(failures).toEqual([]);

      // Each response must carry a valid 200-D, L2-normalised embedding.
      for (const res of responses) {
        const body = await res.json();
        expect(body.dimensions).toBe(200);
        expect(body.embeddings[0].vector).toHaveLength(200);
        expect(body.model).toBe("onnx-cbramod-foundation-200d");
        expect(body.vector_indexed).toBe(1);
      }

      // Latency stats per request (approx via elapsed/n).
      const perReqMs = elapsed / n;
      console.log(
        `[Gate3] n=${n} elapsed=${elapsed.toFixed(1)}ms per_req~${perReqMs.toFixed(1)}ms status=${statuses.join(",")}`,
      );
      expect(perReqMs).toBeGreaterThan(0);
    }, 30_000);
  }

  it("shared cached adapter does not corrupt concurrent requests", async () => {
    // The route shares a single cachedAdapter (singleton) across all requests.
    // Fire 10 concurrent requests and assert every returned vector stays 200-D + L2-normalised,
    // proving the shared ONNX session (mocked here) is not a corruption source.
    const n = 10;
    const reqs = Array.from({ length: n }, (_, i) => buildRequest(i));
    const responses = await Promise.all(reqs.map((r) => callFoundation(r)));
    for (const res of responses) {
      const body = await res.json();
      expect(res.status).toBe(200);
      expect(body.embeddings[0].vector).toHaveLength(200);
      expect(body.embeddings[0].model).toBe("onnx-cbramod-foundation-200d");
    }
    // embedFoundationWindows was invoked exactly once per request (no dropped/queued extras).
    expect(mockEmbedFoundationWindows).toHaveBeenCalledTimes(n);
  });
});
